//
// ПЛАНИРОВЩИК НАРЕЗКИ: делит изображение на горизонтальные полосы строк.
// Каждая полоса — самостоятельное задание для пула потоков: она обрабатывается
// одним рабочим потоком и собирается обратно по своим границам.
//
// ВАЖНО: высота изображения НЕ обязана делиться на число полос нацело.
// Пример из реального запуска: высота 1604, полос 64 -> базовая высота 25,
// остаток 4. Остаток раскладывается «по одной строке» в ПЕРВЫЕ полосы:
//     rows = height / count + (i < height % count ? 1 : 0);
// поэтому первые 4 полосы имеют 26 строк, остальные — 25, и вместе они
// покрывают ровно 1604 строки. Сборка копирует каждую полосу по ЕЁ
// собственным границам, а не по «одинаковой высоте для всех» — это защищает
// от классической ошибки выхода за границы буфера на последней полосе.
// ============================================================================
using System;
using System.Collections.Generic;

namespace Lab4Variant18.Core
{
    // План одной полосы: номер и границы строк в полуинтервале [Y0; Y1).
    // Границы вычисляются один раз при нарезке и дальше используются и для
    // обработки, и для сборки — единый источник правды о геометрии полосы.
    internal sealed class StripPlan
    {
        public readonly int Index; // номер полосы (попадает в журнал)
        public readonly int Y0;    // первая строка полосы
        public readonly int Y1;    // строка ЗА последней (правая граница)
        public readonly int Rows;  // Y1 - Y0 — сколько строк в полосе

        public StripPlan(int index, int y0, int y1)
        {
            Index = index;
            Y0 = y0;
            Y1 = y1;
            Rows = y1 - y0;
        }
    }

    // Расчёт числа полос и их границ. Класс статический: состояния не имеет,
    // поэтому его методы безопасно вызывать из любого потока.
    internal static class StripPlanner
    {
        // Сколько полос нарезать: не меньше 16 (чтобы занять любое число ядер,
        // даже слабой машины) и не больше высоты изображения (полоса не бывает
        // пустой — иначе ей нечего обрабатывать).
        public static int ChooseStripCount(int height, int cores)
        {
            return Math.Min(height, Math.Max(16, cores * 8));
        }

        // Строит список полос, покрывающий строки [0; height) без пропусков
        // и перекрытий: следующая полоса начинается ровно там, где кончилась
        // предыдущая, а последняя полоса заканчивается на строке height.
        public static List<StripPlan> Build(int height, int stripCount)
        {
            List<StripPlan> plans = new List<StripPlan>(stripCount);
            for (int s = 0, y = 0; s < stripCount; s++)
            {
                // Базовая высота полосы + 1 строка остатка для первых полос.
                int rows = height / stripCount + (s < height % stripCount ? 1 : 0);
                int y0 = y;
                int y1 = y0 + rows;
                y = y1; // курсор сдвигается на конец текущей полосы
                plans.Add(new StripPlan(s, y0, y1));
            }
            return plans;
        }
    }
}
