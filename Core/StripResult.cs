namespace Lab4Variant18.Core
{
    // Неизменяемый (immutable) объект: после создания поля не меняются,
    // поэтому читать его из любого потока безопасно даже без блокировки.
    internal sealed class StripResult
    {
        public readonly int Y0;        // первая строка полосы (отсчёт от 0 сверху)
        public readonly int Y1;        // строка ЗА последней строкой полосы
        public readonly byte[] Pixels; // обработанные пиксели полосы (формат BGRA)

        // pixels содержит ровно (Y1 - Y0) * width * 4 байт: строки полосы,
        // записанные подряд. При сборке результата этот блок копируется в
        // общий буфер по смещению Y0 * width * 4 — по собственным границам
        // полосы, а не по «одинаковой высоте для всех полос».
        public StripResult(int y0, int y1, byte[] pixels)
        {
            Y0 = y0;
            Y1 = y1;
            Pixels = pixels;
        }
    }
}
