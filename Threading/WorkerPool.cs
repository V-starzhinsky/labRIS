// ============================================================================
// Лабораторная работа 4. Вариант 18 — «Выделение заданного цветового
// диапазона в маску». Файл: Threading/WorkerPool.cs
//
// СОБСТВЕННЫЙ ПУЛ ПОТОКОВ фиксированного размера с общей очередью заданий.
//
// Здесь живут ТРИ механизма синхронизации из пяти, заявленных в работе:
//   1) lock (Monitor)   — критическая секция вокруг общей очереди заданий;
//   2) AutoResetEvent   — сигнал «появилось задание», будит ОДИН поток;
//   3) ManualResetEvent — сигнал «пул останавливается», будит ВСЕ потоки.
//
// Почему пул свой, а не ThreadPool из .NET: смысл лабораторной — показать
// работу примитивов синхронизации «вручную». Рабочие потоки крутят один и
// тот же цикл WorkerLoop: «взять задание из очереди -> выполнить -> повторить»,
// а между заданиями спят на WaitAny(«задание», «остановка»).
// ============================================================================
using System;
using System.Collections.Generic;
using System.Threading;

namespace Lab4Variant18.Threading
{
    // ------------------------------------------------------------------
    // Пул потоков: N рабочих потоков + общая очередь делегатов Action.
    // Все обращения к очереди выполняются строго внутри lock (_queueGate),
    // поэтому состояние очереди не может быть испорчено гонкой потоков.
    // Класс реализует IDisposable: после Shutdown() гарантируется, что ни
    // один рабочий поток не остаётся живым (Join для каждого потока).
    // ------------------------------------------------------------------
    internal class WorkerPool : IDisposable
    {
        // Общая очередь заданий. Потокобезопасность обеспечивает lock по
        // _queueGate: Enqueue/Dequeue/Count выполняются только внутри него.
        private readonly Queue<Action> _queue = new Queue<Action>();

        // Монитор (объект блокировки) для критических секций очереди.
        private readonly object _queueGate = new object();

        // Сигнал «появилось задание». AutoResetEvent «сбрасывается сам»:
        // Set() будит ровно ОДИН ожидающий поток и возвращает событие в
        // несигнальное состояние. Поэтому, если заданий несколько, а проснулся
        // только один поток, в WorkerLoop есть «эстафета» — повторный Set().
        private readonly AutoResetEvent _taskAvailable = new AutoResetEvent(false);

        // Сигнал «пул останавливается». В отличие от AutoResetEvent,
        // ManualResetEvent остаётся сигнальным после Set(), поэтому ОДИН
        // вызов Set() будит ВСЕ рабочие потоки сразу — именно это и нужно
        // при остановке пула.
        private readonly ManualResetEvent _stopping = new ManualResetEvent(false);

        // Список рабочих потоков — нужен для Join в Shutdown().
        private readonly List<Thread> _workers = new List<Thread>();

        // Конструктор создаёт и запускает заданное число рабочих потоков.
        // Потоки фоновые (IsBackground = true): они не мешают процессу
        // завершиться, даже если форму закрыли без явного Shutdown().
        public WorkerPool(int size)
        {
            for (int i = 0; i < size; i++)
            {
                Thread t = new Thread(WorkerLoop);
                t.Name = "PoolWorker-" + (i + 1); // имя видно в журнале конвейера
                t.IsBackground = true;
                _workers.Add(t);
                t.Start(); // поток сразу входит в WorkerLoop и засыпает на WaitAny
            }
        }

        // Планировщик кладёт задание в общую очередь и будит один поток пула.
        // В очередь кладём под lock; сигнал Set() — уже ВНЕ lock: поток,
        // которого разбудил сигнал, всё равно сначала должен войти в lock,
        // чтобы забрать задание, поэтому держать монитор во время Set не нужно.
        public void Submit(Action task)
        {
            lock (_queueGate)                // --- критическая секция очереди ---
            {
                _queue.Enqueue(task);
            }
            _taskAvailable.Set();            // сигнал «появилось задание»
        }

        // Главный цикл рабочего потока. Пока пул жив, поток повторяет одно
        // и то же: попытаться взять задание (под lock), выполнить его вне
        // блокировки, а если заданий нет — уснуть на WaitAny до события
        // «появилось задание» или «пул останавливается».
        private void WorkerLoop()
        {
            // Массив ожиданий для WaitAny: [0] «есть задание», [1] «остановка».
            WaitHandle[] handles = new WaitHandle[] { _taskAvailable, _stopping };
            while (true)
            {
                Action task = null;
                lock (_queueGate)            // --- критическая секция очереди ---
                {
                    if (_queue.Count > 0) task = _queue.Dequeue();
                }

                if (task != null)
                {
                    task(); // выполняем задание ВНЕ lock — иначе остальные
                            // потоки не могли бы параллельно брать свои задания
                    // «Эстафета»: AutoResetEvent не накапливает сигналы, поэтому
                    // если в очереди ещё остались задания — будим следующий
                    // поток, чтобы работники не простаивали.
                    bool more = false;
                    lock (_queueGate) { more = _queue.Count > 0; }
                    if (more) _taskAvailable.Set();
                    continue;
                }

                // Очередь пуста: либо пул уже останавливают, либо спим.
                if (_stopping.WaitOne(0)) return;        // сигнал уже поднят
                int what = WaitHandle.WaitAny(handles);  // задание ИЛИ остановка
                if (what == 1) return;                   // сигнал остановки пула
                // what == 0: появилось задание — продолжаем цикл и забираем его.
            }
        }

        // Корректная остановка: выбрасываем невыполненные задания, поднимаем
        // ManualResetEvent (будит ВСЕ потоки) и дожидаемся фактического
        // завершения каждого потока (Join) — «зависших» потоков не остаётся.
        // Метод идемпотентен: повторный вызов (например, из finally и из
        // Dispose) ничего не портит — события и Join просто срабатывают заново.
        public void Shutdown()
        {
            lock (_queueGate) { _queue.Clear(); }
            _stopping.Set();
            foreach (Thread t in _workers) t.Join();
        }

        // IDisposable: Dispose сводится к Shutdown (удобно для using).
        public void Dispose()
        {
            Shutdown();
        }
    }
}
